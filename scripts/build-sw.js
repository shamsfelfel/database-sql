/* build-sw.js — regenerates ../sw.js with an accurate precache manifest of every
   shipped file (HTML pages, CSS, JS, vendored alasql, fonts, data bundle, icons,
   manifest). Run from anywhere:  node scripts/build-sw.js
   Re-run after ANY change to a shipped file (run it last, after build-data.js):
   the cache version is a content hash, so installed clients re-download exactly
   when something actually changed. */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');

function walk(dir, acc, filter) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return;
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const rel = dir ? dir + '/' + e.name : e.name;
    if (e.isDirectory()) walk(rel, acc, filter);
    else if (filter(rel)) acc.push(rel);
  }
}

const files = [];
walk('', files, r => /\.html$/.test(r) && !r.includes('/')); // root html (index.html)
['chapters', 'lessons', 'tests', 'exams'].forEach(d => walk(d, files, r => /\.html$/.test(r)));
walk('assets', files, r => /\.(css|js|woff2)$/.test(r));
walk('assets/icons', files, r => /\.png$/.test(r));
if (fs.existsSync(path.join(ROOT, 'manifest.webmanifest'))) files.push('manifest.webmanifest');

const set = Array.from(new Set(files)).sort();
const precache = ['./'].concat(set);
// The cache name carries a hash of every precached file's contents, so ANY change
// to a shipped file (not just adding/removing one) yields a new sw.js — browsers
// only re-install a service worker when sw.js itself changes byte-for-byte.
const hash = crypto.createHash('sha256');
set.forEach(rel => { hash.update(rel + '\0'); hash.update(fs.readFileSync(path.join(ROOT, rel))); });
const VERSION = 'sqllab-' + new Date().toISOString().slice(0, 10).replace(/-/g, '') + '-' + hash.digest('hex').slice(0, 10);

const sw = `/* sw.js — SQL Lab service worker (generated by scripts/build-sw.js).
   Precaches the whole static site on install so it works fully offline and is
   installable as a PWA on Windows, Android, and iOS. Cache-first for assets;
   network-first-with-cache-fallback for navigations (so an online visit picks up
   updates, while offline still serves the cached page). Bump CACHE to invalidate. */
'use strict';

var CACHE = '${VERSION}';

/* Everything is listed relative to the service worker's own location (the site
   root), so it resolves correctly whether the site is served from a domain root
   or a GitHub Pages project subpath. */
var PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      /* add one-by-one so a single 404 can't abort the whole precache. */
      return Promise.all(PRECACHE.map(function (url) {
        return cache.add(new Request(url, { cache: 'reload' })).catch(function () {});
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k !== CACHE) return caches.delete(k);
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (event) {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never touch cross-origin

  // Navigations: network first (fresh when online), fall back to cached page, then
  // to the cached start page, so offline never shows a browser error.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).then(function (res) {
        var copy = res.clone();
        caches.open(CACHE).then(function (c) { c.put(req, copy); });
        return res;
      }).catch(function () {
        return caches.match(req).then(function (hit) {
          return hit || caches.match('index.html').then(function (i) { return i || caches.match('./'); });
        });
      })
    );
    return;
  }

  // Assets: cache-first, fall back to network and populate the cache.
  event.respondWith(
    caches.match(req).then(function (hit) {
      return hit || fetch(req).then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      });
    })
  );
});
`;

fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log('wrote sw.js — cache "' + VERSION + '", ' + precache.length + ' precached URLs');
