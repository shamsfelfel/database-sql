/* build-data.js — regenerates ../assets/js/data.js from the JSON snapshots in
   /data/case-*. The JSON files stay the source of truth; the bundle is what the
   pages actually load (via a plain <script> tag), so the course runs from a
   file:// URL with nothing fetched at runtime.  Run:  node scripts/build-data.js

   Shape: window.SQLLAB_DATA[case][key] = { tables: { name: [rows] } }
   where case is a|b|c (the three teaching cases) or d|e (the exam databases),
   and key is a chapter number (chapter-N.json) or the string 'exam'
   (chapter-exam.json, used by the final exams). */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const CASES = ['a', 'b', 'c', 'd', 'e'];
const MAX_CHAPTER = 9;

const out = {};
for (const cs of CASES) {
  const dir = path.join(ROOT, 'data', 'case-' + cs);
  if (!fs.existsSync(dir)) continue;
  const bucket = {};
  for (let ch = 1; ch <= MAX_CHAPTER; ch++) {
    const p = path.join(dir, 'chapter-' + ch + '.json');
    if (fs.existsSync(p)) bucket[ch] = JSON.parse(fs.readFileSync(p, 'utf8'));
  }
  const exam = path.join(dir, 'chapter-exam.json');
  if (fs.existsSync(exam)) bucket.exam = JSON.parse(fs.readFileSync(exam, 'utf8'));
  if (Object.keys(bucket).length) out[cs] = bucket;
}

fs.writeFileSync(
  path.join(ROOT, 'assets', 'js', 'data.js'),
  '/* data.js — generated by scripts/build-data.js. Do not edit; edit /data/case-*\n'
  + '   and re-run the generator. Holds every case snapshot so the site needs no fetch. */\n'
  + 'window.SQLLAB_DATA = ' + JSON.stringify(out, null, 2) + ';\n'
);

const summary = Object.keys(out).map(cs => cs + ':[' + Object.keys(out[cs]).join(',') + ']').join('  ');
console.log('wrote assets/js/data.js — ' + summary);
